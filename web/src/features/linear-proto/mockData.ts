function assigneeAt(index: number | null): Assignee | null {
  if (index === null) return null;
  return MOCK_ASSIGNEES[index] ?? null;
}

function labelsAt(indices: readonly number[]): Label[] {
  return indices.map((index) => MOCK_LABELS[index] ?? UNKNOWN_LABEL);
}

function projectAt(index: number | null): string | null {
  if (index === null) return null;
  return MOCK_PROJECTS[index] ?? null;
}

